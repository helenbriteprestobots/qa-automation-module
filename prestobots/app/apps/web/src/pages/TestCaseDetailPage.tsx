import { AREA_LABELS } from '@ctp/shared';
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { Archive, ArrowLeft, ExternalLink, Play, RotateCcw, Sparkles } from 'lucide-react';
import { Link, useNavigate, useParams } from 'react-router-dom';

import { api } from '../api';
import { StatusPill } from '../components/StatusPill';
import { StepsList } from '../components/StepsList';
import { Button, Card, ErrorBox, Loading, PageTitle } from '../components/ui';
import { formatDateTime } from '../format';

const ORIGIN_LABELS = {
  starter: 'Starter example',
  generated: 'Generated by AI',
  manual: 'Written by an admin',
} as const;

export const TestCaseDetailPage = () => {
  const { id = '' } = useParams();
  const navigate = useNavigate();
  const queryClient = useQueryClient();

  const detail = useQuery({ queryKey: ['test-case', id], queryFn: () => api.testCase(id) });
  const startRun = useMutation({
    mutationFn: api.startRun,
    onSuccess: (run) => navigate(`/runs/${run.id}`),
  });
  const setStatus = useMutation({
    mutationFn: (status: 'active' | 'archived') => api.setTestCaseStatus(id, status),
    onSuccess: () => {
      void queryClient.invalidateQueries({ queryKey: ['test-case', id] });
      void queryClient.invalidateQueries({ queryKey: ['test-cases'] });
    },
  });

  if (detail.isLoading) return <Loading />;
  if (!detail.data) return <ErrorBox error={detail.error ?? 'Not found'} />;

  const { testCase, history, jiraCards = [] } = detail.data;

  return (
    <>
      <Link to="/test-cases" className="mb-4 inline-flex items-center gap-1 text-sm text-slate-600 hover:text-slate-900">
        <ArrowLeft className="h-4 w-4" aria-hidden /> Test cases
      </Link>

      <PageTitle
        title={
          <span className="flex flex-wrap items-center gap-3">
            <span className="font-mono text-base text-slate-500">{testCase.id}</span>
            {testCase.title}
          </span>
        }
        subtitle={
          <span className="flex flex-wrap items-center gap-2">
            <StatusPill status={testCase.status} />
            <span>{AREA_LABELS[testCase.area]}</span>
            <span className="text-slate-400">·</span>
            <span>{ORIGIN_LABELS[testCase.origin]}</span>
          </span>
        }
        actions={
          <>
            <Button variant="secondary" onClick={() => navigate(`/test-cases/${testCase.id}/edit`)}>
              <Sparkles className="h-4 w-4" aria-hidden /> Change with AI
            </Button>
            {testCase.status === 'proposed' && (
              <Button variant="secondary" onClick={() => setStatus.mutate('active')} disabled={setStatus.isPending}>
                Approve
              </Button>
            )}
            {testCase.status === 'archived' ? (
              <Button variant="secondary" onClick={() => setStatus.mutate('active')} disabled={setStatus.isPending}>
                <RotateCcw className="h-4 w-4" aria-hidden /> Activate
              </Button>
            ) : (
              <Button variant="secondary" onClick={() => setStatus.mutate('archived')} disabled={setStatus.isPending}>
                <Archive className="h-4 w-4" aria-hidden /> Archive
              </Button>
            )}
            <Button onClick={() => startRun.mutate({ testCaseIds: [testCase.id] })} disabled={startRun.isPending}>
              <Play className="h-4 w-4" aria-hidden /> Run this test
            </Button>
          </>
        }
      />

      <ErrorBox error={startRun.error ?? setStatus.error} />

      <div className="grid gap-6 lg:grid-cols-3">
        <div className="space-y-6 lg:col-span-2">
          <Card className="p-5">
            <h2 className="text-sm font-semibold uppercase tracking-wide text-slate-500">Story</h2>
            <p className="mt-2">{testCase.story}</p>
          </Card>

          <Card className="p-5">
            <h2 className="text-sm font-semibold uppercase tracking-wide text-slate-500">Steps</h2>
            <div className="mt-3">
              <StepsList steps={testCase.steps} />
            </div>
          </Card>
        </div>

        <div className="space-y-6">
        <Card className="h-fit p-5">
          <h2 className="text-sm font-semibold uppercase tracking-wide text-slate-500">History</h2>
          {history.length === 0 ? (
            <p className="mt-2 text-sm text-slate-500">Never run.</p>
          ) : (
            <ul className="mt-3 divide-y divide-slate-100">
              {history.map((entry) => (
                <li key={entry.id} className="py-2">
                  <Link to={`/runs/${entry.runId}`} className="flex items-center justify-between gap-2 hover:underline">
                    <span className="text-sm">Run #{entry.runId}</span>
                    <StatusPill status={entry.status} />
                  </Link>
                  <p className="text-xs text-slate-500">{formatDateTime(entry.finishedAt)}</p>
                </li>
              ))}
            </ul>
          )}
        </Card>

        <Card className="h-fit p-5">
          <h2 className="text-sm font-semibold uppercase tracking-wide text-slate-500">Jira cards</h2>
          {jiraCards.length === 0 ? (
            <p className="mt-2 text-sm text-slate-500">None yet. Create one from a failed result in a run report.</p>
          ) : (
            <ul className="mt-3 divide-y divide-slate-100">
              {jiraCards.map((card) => (
                <li key={card.id} className="py-2">
                  <a href={card.url} target="_blank" rel="noreferrer" className="flex items-center gap-1 text-sm text-sky-700 hover:underline">
                    {card.kind === 'created' ? `${card.issueKey} · ${card.issueType}` : `Comment on ${card.issueKey}`}
                    <ExternalLink className="h-3.5 w-3.5" aria-hidden />
                  </a>
                  <p className="text-xs text-slate-500">
                    {formatDateTime(card.createdAt)} · from <Link to={`/runs/${card.runId}`} className="hover:underline">run #{card.runId}</Link>
                  </p>
                </li>
              ))}
            </ul>
          )}
          <p className="mt-3 text-xs text-slate-400">Only links are kept. Check each card's status in Jira.</p>
        </Card>
        </div>
      </div>
    </>
  );
};
